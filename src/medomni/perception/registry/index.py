"""The catalogue index: one row per encoder folder, from its card. It is generated, never edited."""
from datetime import datetime, timezone

import yaml

from . import encoder_dirs
from .cards import load_card


def entries(root=None, ids=()):
    out = []
    for edir in encoder_dirs(ids, root):
        card = load_card(edir)
        out.append({
            "id": card["id"],
            "family": card["family"],
            "modality": card.get("modality"),
            "outputs": [b.get("kind") for b in card.get("outputs") or []],
            "reliability": (card.get("reliability") or {}).get("status"),
            "acceptance": card.get("acceptance"),
            "runnable": (edir / "adapter.py").is_file(),
            "dir": f"encoders/{edir.parent.name}/{edir.name}/",
        })
    return out


def render(root=None, ids=()):
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    return ("# MedOmni encoders: generated by medomni.perception.registry.index, do not edit.\n"
            + yaml.safe_dump({"generated_at": stamp, "encoders": entries(root, ids)},
                             sort_keys=False, allow_unicode=True, width=110))
